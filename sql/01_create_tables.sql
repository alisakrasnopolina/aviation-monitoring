BEGIN;
SET LOCAL search_path = public, pg_temp;
-- Информационная система учета, мониторинга и анализа
-- авиарейсов и задержек аэропорта
-- Практическая работа № 6
-- Создание физической структуры базы данных

-- 1. РОЛИ ПОЛЬЗОВАТЕЛЕЙ

CREATE TABLE app_role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    role_name VARCHAR(50) NOT NULL,

    CONSTRAINT pk_app_role
        PRIMARY KEY (role_id),

    CONSTRAINT uq_app_role_name
        UNIQUE (role_name),

    CONSTRAINT chk_app_role_name
        CHECK (BTRIM(role_name) <> '')
);


-- 2. ПОЛЬЗОВАТЕЛИ

CREATE TABLE app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    login VARCHAR(50) NOT NULL,
    db_login NAME,
    last_name VARCHAR(100) NOT NULL,
    first_name VARCHAR(100) NOT NULL,
    middle_name VARCHAR(100),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    role_id BIGINT NOT NULL,

    CONSTRAINT pk_app_user
        PRIMARY KEY (user_id),

    CONSTRAINT uq_app_user_login
        UNIQUE (login),

    CONSTRAINT uq_app_user_db_login UNIQUE (db_login),

    CONSTRAINT chk_app_user_login
        CHECK (BTRIM(login) <> ''),

    CONSTRAINT fk_app_user_role
        FOREIGN KEY (role_id)
        REFERENCES app_role(role_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

-- 3. АЭРОПОРТЫ

CREATE TABLE airport (
    airport_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    airport_code VARCHAR(3) NOT NULL,
    airport_name VARCHAR(150) NOT NULL,
    city VARCHAR(100) NOT NULL,

    CONSTRAINT pk_airport
        PRIMARY KEY (airport_id),

    CONSTRAINT uq_airport_code
        UNIQUE (airport_code),

    CONSTRAINT chk_airport_code
        CHECK (airport_code ~ '^[A-Z]{3}$')
);

-- 4. АВИАКОМПАНИИ

CREATE TABLE airline (
    airline_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    airline_code VARCHAR(3) NOT NULL,
    airline_name VARCHAR(150) NOT NULL,

    CONSTRAINT pk_airline
        PRIMARY KEY (airline_id),

    CONSTRAINT uq_airline_code
        UNIQUE (airline_code),

    CONSTRAINT chk_airline_code
        CHECK (airline_code ~ '^[A-Z0-9]{2,3}$')
);

-- 5. СТАТУСЫ РЕЙСОВ

CREATE TABLE flight_status (
    status_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    status_name VARCHAR(50) NOT NULL,

    CONSTRAINT pk_flight_status
        PRIMARY KEY (status_id),

    CONSTRAINT uq_flight_status_name
        UNIQUE (status_name),

    CONSTRAINT chk_flight_status_name
        CHECK (BTRIM(status_name) <> '')
);

-- 6. ПРИЧИНЫ ЗАДЕРЖЕК

CREATE TABLE delay_reason (
    reason_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reason_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),

    CONSTRAINT pk_delay_reason
        PRIMARY KEY (reason_id),

    CONSTRAINT uq_delay_reason_name
        UNIQUE (reason_name),

    CONSTRAINT chk_delay_reason_name
        CHECK (BTRIM(reason_name) <> '')
);

-- 7. РЕЙСЫ

CREATE TABLE flight (
    flight_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    flight_number VARCHAR(10) NOT NULL,
    airline_id BIGINT NOT NULL,
    departure_airport_id BIGINT NOT NULL,
    arrival_airport_id BIGINT NOT NULL,

    CONSTRAINT pk_flight
        PRIMARY KEY (flight_id),

    CONSTRAINT uq_flight
        UNIQUE (
            airline_id,
            flight_number,
            departure_airport_id,
            arrival_airport_id
        ),

    CONSTRAINT chk_flight_number
        CHECK (BTRIM(flight_number) <> ''),

    CONSTRAINT chk_flight_different_airports
        CHECK (departure_airport_id <> arrival_airport_id),

    CONSTRAINT fk_flight_airline
        FOREIGN KEY (airline_id)
        REFERENCES airline(airline_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_flight_departure_airport
        FOREIGN KEY (departure_airport_id)
        REFERENCES airport(airport_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_flight_arrival_airport
        FOREIGN KEY (arrival_airport_id)
        REFERENCES airport(airport_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

-- 8. ВЫПОЛНЕНИЯ РЕЙСОВ

CREATE TABLE flight_instance (
    flight_instance_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    flight_id BIGINT NOT NULL,
    status_id BIGINT NOT NULL,
    scheduled_departure TIMESTAMP NOT NULL,
    scheduled_arrival TIMESTAMP NOT NULL,
    actual_departure TIMESTAMP,
    actual_arrival TIMESTAMP,

    CONSTRAINT pk_flight_instance
        PRIMARY KEY (flight_instance_id),

    CONSTRAINT uq_flight_instance
        UNIQUE (flight_id, scheduled_departure),

    CONSTRAINT chk_actual_arrival_requires_departure
        CHECK (
            actual_arrival IS NULL
            OR actual_departure IS NOT NULL
        ),
        
    CONSTRAINT chk_scheduled_arrival_after_departure
        CHECK (scheduled_arrival > scheduled_departure),

    CONSTRAINT chk_actual_arrival_after_departure
        CHECK (
            actual_arrival IS NULL
            OR (
                actual_departure IS NOT NULL
                AND actual_arrival > actual_departure
            )
        ),

    CONSTRAINT fk_flight_instance_flight
        FOREIGN KEY (flight_id)
        REFERENCES flight(flight_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_flight_instance_status
        FOREIGN KEY (status_id)
        REFERENCES flight_status(status_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

-- 9. ЗАДЕРЖКИ

CREATE TABLE delay (
    delay_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    flight_instance_id BIGINT NOT NULL,
    reason_id BIGINT,

    CONSTRAINT pk_delay
        PRIMARY KEY (delay_id),

    CONSTRAINT uq_delay_flight_instance
        UNIQUE (flight_instance_id),

    CONSTRAINT fk_delay_flight_instance
        FOREIGN KEY (flight_instance_id)
        REFERENCES flight_instance(flight_instance_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_delay_reason
        FOREIGN KEY (reason_id)
        REFERENCES delay_reason(reason_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);

-- 10. ИСТОРИЯ СОСТОЯНИЙ

CREATE TABLE status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    flight_instance_id BIGINT NOT NULL,
    previous_status_id BIGINT,
    new_status_id BIGINT NOT NULL,
    changed_by_user_id BIGINT NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_status_history
        PRIMARY KEY (history_id),

    CONSTRAINT chk_status_change
        CHECK (
            previous_status_id IS NULL
            OR previous_status_id <> new_status_id
        ),

    CONSTRAINT fk_status_history_flight_instance
        FOREIGN KEY (flight_instance_id)
        REFERENCES flight_instance(flight_instance_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_status_history_previous_status
        FOREIGN KEY (previous_status_id)
        REFERENCES flight_status(status_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_status_history_new_status
        FOREIGN KEY (new_status_id)
        REFERENCES flight_status(status_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT fk_status_history_user
        FOREIGN KEY (changed_by_user_id)
        REFERENCES app_user(user_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT
);
COMMIT;
